from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

from someip_ros2_bridge.codec import PRIMITIVES
from someip_ros2_bridge.config import ConfigError
from someip_ros2_bridge.definitions import DefinitionError, Definitions, Service, load_definitions

DEFAULT_DEFINITIONS = Path(__file__).resolve().parents[2] / "system_definition/someip"

STD_MSGS = {t: t[0].upper() + t[1:].replace("int", "Int") for t in PRIMITIVES}


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Generate a bridge config from system_definition.")
    parser.add_argument("services", nargs="*", help="service names (none: list them)")
    parser.add_argument("--definitions", type=Path, default=DEFAULT_DEFINITIONS)
    parser.add_argument("-o", "--output", type=Path, help="write here instead of stdout")
    parser.add_argument("--local-ip", default="127.0.0.1", help="IP or interface, e.g. eth0")
    parser.add_argument("--first-port", type=int, default=10319, help="client_port of 1st service")
    args = parser.parse_args(argv)
    try:
        definitions = load_definitions(args.definitions)
        if not args.services:
            print(list_services(definitions))
            return
        text = generate(
            definitions,
            args.services,
            definitions_path=_relative(args.definitions, args.output),
            local_ip=args.local_ip,
            first_port=args.first_port,
        )
    except (ConfigError, DefinitionError) as error:
        sys.exit(f"error: {error}")
    if args.output:
        args.output.write_text(text, encoding="utf-8")
        print(
            f"wrote {args.output}; check it with: someip-ros2-bridge --config {args.output} --check"
        )
    else:
        print(text, end="")


def list_services(definitions: Definitions) -> str:
    lines = ["Available services (make_config.py NAME [NAME ...] -o my.yaml):"]
    for service in sorted(definitions.services.values(), key=lambda s: s.id):
        lines.append(
            f"  {service.name:<22} id {service.id:<4} "
            f"{len(service.events)} events, {len(service.methods)} methods"
        )
    return "\n".join(lines)


def generate(
    definitions: Definitions,
    services: list[str],
    *,
    definitions_path: str,
    local_ip: str = "127.0.0.1",
    first_port: int = 10319,
) -> str:
    unknown = [name for name in services if name not in definitions.services]
    if unknown:
        known = ", ".join(sorted(definitions.services))
        raise ConfigError(f"Unknown service {', '.join(unknown)} (known: {known})")

    lines = [
        f"# Generated by make_config.py {' '.join(services)}",
        "# Edit freely; every option is listed in README.md (Config).",
        f"definitions: {definitions_path}",
        "",
        "network:",
        f"  local_ip: {local_ip}             # this PC: IP or interface (eth0, wlan0)",
        "  sd_multicast_ip: 224.224.224.245",
        "  sd_port: 30490",
        "  # board_ip: 203.0.113.7         # board not on this LAN (router, VPN, internet)",
        "",
        "services:",
    ]
    for port, name in enumerate(dict.fromkeys(services), start=first_port):
        lines += _service(definitions, definitions.services[name], port)
    return "\n".join(lines) + "\n"


def _service(definitions: Definitions, service: Service, port: int) -> list[str]:
    prefix = f"someip/{snake_case(service.name)}"
    lines = [
        f"  {service.name}:  # service id {service.id}, "
        f"v{service.major_version}.{service.minor_version}",
        "    instance_id: 1",
        f"    client_port: {port}",
    ]
    if service.events:
        lines.append("    events:")
    for event in service.events.values():
        topic = f"{prefix}/{snake_case(event.name)}"
        if event.type in STD_MSGS:
            lines += [
                f"      {event.name}:  # {event.type}",
                f"        topic: {topic}",
                f"        type: std_msgs/msg/{STD_MSGS[event.type]}",
                "        fields: {data: {}}",
            ]
            continue
        fields = definitions.structs.get(event.type, {})
        lines += [
            f"      # {event.name}: struct {event.type}. Choose a ROS message, then uncomment:",
            f"      # {event.name}:",
            f"      #   topic: {topic}",
            "      #   type: gs_interfaces/msg/<Message>",
            "      #   fields:                 # <ros_field>: <struct field>",
            *(f"      #     <ros_field>: {field}  # {type_}" for field, type_ in fields.items()),
        ]
    if service.methods:
        lines.append("    methods:")
    for method in service.methods.values():
        signature = f"{method.in_type} -> {method.out_type}"
        if method.in_type == "void":
            body = ["        type: std_msgs/msg/Empty"]
        elif method.in_type in STD_MSGS:
            body = [f"        type: std_msgs/msg/{STD_MSGS[method.in_type]}", "        field: data"]
        else:
            lines.append(f"      # {method.name}: {signature} - struct arguments not supported")
            continue
        lines += [
            f"      {method.name}:  # {signature}",
            f"        topic: {prefix}/{snake_case(method.name)}",
            *body,
        ]
    return lines


def snake_case(name: str) -> str:
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()


def _relative(definitions: Path, output: Path | None) -> str:
    base = output.resolve().parent if output else Path.cwd()
    return os.path.relpath(definitions.resolve(), base)


if __name__ == "__main__":
    main()
